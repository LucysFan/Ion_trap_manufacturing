"""Workflow 09: movable-x-knot, full-contour C4v open-centre island GA.

One common set of movable longitudinal knots defines both inner and outer RF
edges of one C4v fundamental arm. The four arms are generated by the existing
conventional X-junction template. Beyond the movable core lock point, offsets
are exactly zero and the geometry returns to the ordinary straight transport
cross. No central RF cross is added.

Optimization objectives are physical only: peak RF-null height deviation and
RF pseudopotential barrier. Geometry validity, rail width, endpoint attachment,
template slope restrictions and complete RF-null traces remain hard checks.
"""
