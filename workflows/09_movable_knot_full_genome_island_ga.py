class BEMField:
    def __init__(self, bem: FixedMeshBEM, charge: Any):
        self.bem, self.charge = bem, charge

    def electric_field(self, x_m: float, y_m: float, z_m: float):
        values = self.bem.field_batch(np.array([x_m]), np.array([y_m]), np.array([z_m]), self.charge)
        return tuple(map(float, self.bem.asnumpy(values)[0, 0]))


def repair(x: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=float).copy()
    if x.shape != (N_GENES,) or not np.all(np.isfinite(x)):
        raise ValueError(f"expected {N_GENES} finite genes")
    return np.clip(x, LOW, HIGH)


def decode(x: np.ndarray):
    x = repair(x)
    lock = float(x[LOCK])
    knots = softmax_gap_knots(x[GAPS], lock_m=lock, min_gap_m=MIN_GAP_M)
    inner = np.r_[0.0, x[INNER], 0.0]
    outer = np.r_[0.0, x[OUTER], 0.0]
    return knots, inner, outer


def baseline() -> np.ndarray:
    x = np.zeros(N_GENES)
    x[LOCK] = FIXED_CORE_KNOTS_M[-1]
    x[GAPS] = fixed_knots_to_logits(FIXED_CORE_KNOTS_M, min_gap_m=MIN_GAP_M)
    x[CENTER_IN:] = [-25e-6, 20e-6, 30e-6, 150e-6, 2.0, 0.0, 70e-6, 25e-6]
    return x


def conventional_cross() -> np.ndarray:
    """Exact conventional straight-cross seed: all movable contour offsets zero."""
    return baseline()


def seeds() -> list[tuple[str, np.ndarray]]:
    base = baseline()
    inner = base.copy(); inner[INNER] = np.array([-4, -8, -12, -12, -8, -4, -2], dtype=float)*1e-6
    outer = base.copy(); outer[OUTER] = np.array([2, 5, 9, 11, 8, 4, 2], dtype=float)*1e-6
    coupled = base.copy(); coupled[INNER] = np.array([-3, -7, -11, -13, -9, -5, -2], dtype=float)*1e-6
    coupled[OUTER] = np.array([2, 5, 10, 12, 8, 4, 1], dtype=float)*1e-6
    packed = base.copy(); packed[GAPS] = np.array([1.4, 1.0, .6, .1, -.3, -.7, -1.0, -1.2]); packed[LOCK] = 130e-6
    return [("conventional_exact", conventional_cross()), ("inner", inner), ("outer", outer),
            ("coupled", coupled), ("packed_x", packed)]


def parameters(x: np.ndarray):
    knots, inner, outer = decode(x)
    contour = MovableKnotContour(knots, inner, outer, lock_m=float(x[LOCK]), min_gap_m=MIN_GAP_M)
    return build_movable_knot_parameters(
        contour=contour, inner_edge_shift_at_centre_m=float(x[CENTER_IN]),
        outer_edge_shift_at_centre_m=float(x[CENTER_OUT]), rf_start_radius_override_m=float(x[START]),
        taper_length_m=float(x[LENGTH]), taper_power=float(x[POWER]),
        outer_bulge_amplitude_m=float(x[BULGE]), outer_bulge_center_m=float(x[BULGE_CENTER]),
        outer_bulge_sigma_m=float(x[BULGE_WIDTH]))


def rejected(reason: str, stage: str) -> dict[str, Any]:
    return dict(valid=False, verified=False, reason=reason, stage=stage, dz_peak_m=np.inf,
                dz_rms_m=np.inf, barrier_ev=np.inf, lateral_peak_m=np.inf, panels=0, points=0, converged=0)


