def evaluate(genome: np.ndarray, cfg: Settings, stage="coarse", retain=False):
    x = repair(genome)
    try:
        p = parameters(x)
        report = check_x_junction_manufacturability(p)
        if not report.valid:
            return rejected("geometry: "+"; ".join(map(str, report.messages)), stage), None
        s = np.linspace(0, p.arm_length_m, 2001)
        rin, rout = p.rail_boundaries_m(s)
        if np.min(rin) <= .5e-6:
            return rejected("inner clearance", stage), None
        if np.min(rout-rin) < cfg.rail_min_width_m:
            return rejected("rail width", stage), None
        model = mesh(p, cfg.fast and stage=="coarse")
        if model.n_panels > cfg.max_panels:
            return rejected("panel limit", stage), None
        bem = FixedMeshBEM(model.bem.panels_m, backend=cfg.backend)
        bem.assemble(block_rows=64); bem.factorize(); bem.release_matrix()
        charge = bem.solve_masks(model.bem.electrode_voltages_v); field = BEMField(bem, charge)
        n = cfg.fine_points if stage=="fine" else cfg.coarse_points
        trace = trace_rf_transverse_minimum(field, np.linspace(-350e-6,350e-6,n), initial_y_m=0.,
                                             initial_z_m=cfg.target_z_m, residual_tolerance_v_m=1e-3,
                                             max_transverse_shift_m=25e-6)
        converged = np.asarray(trace.converged, bool); z, y = np.asarray(trace.z_m,float), np.asarray(trace.y_m,float)
        if not trace.valid or converged.shape!=(n,) or not np.all(converged):
            return rejected("incomplete trace", stage), None
        if not np.all(np.isfinite(z)) or not np.all(np.isfinite(y)):
            return rejected("nonfinite trace", stage), None
        pseudo = np.asarray(pseudopotential_profile_ev(field,trace,rf_voltage_peak_v=cfg.rf_peak_v,
                          rf_angular_frequency_rad_s=RF_ANGULAR_FREQUENCY_RAD_S),float)
        barrier = compute_barrier_metrics(pseudo,trace)
        if not barrier.valid or pseudo.shape!=(n,) or not np.all(np.isfinite(pseudo)):
            return rejected("invalid pseudopotential", stage), None
        dz = z-cfg.target_z_m; peak=float(np.max(np.abs(dz))); rms=float(np.sqrt(np.mean(dz**2)))
        lateral,U=float(np.max(np.abs(y))),float(barrier.barrier_height_ev)
        if not np.all(np.isfinite([peak,rms,lateral,U])):
            return rejected("nonfinite metrics", stage), None
        return dict(valid=True,verified=bool(stage=="fine" and peak<cfg.dz_limit_m and U<cfg.barrier_limit_ev and lateral<cfg.lateral_limit_m),
                    reason="ok",stage=stage,backend=bem.backend_name,dz_peak_m=peak,dz_rms_m=rms,barrier_ev=U,
                    lateral_peak_m=lateral,barrier_reference_ev=float(barrier.reference_energy_ev),panels=int(model.n_panels),
                    points=n,converged=int(np.sum(converged))), (model,trace,pseudo) if retain else None
    except Exception as err:
        if cfg.backend=="cuda" and "out of memory" in str(err).lower():
            raise RuntimeError("CUDA OOM: reduce --max-panels or use --fast") from err
        return rejected(f"geometry/BEM error: {type(err).__name__}: {str(err).replace(chr(10),' ').strip()}", stage), None


def dominates(a: Individual,b: Individual) -> bool:
    if a.valid!=b.valid: return a.valid
    return bool(a.valid and np.all(a.objectives<=b.objectives) and np.any(a.objectives<b.objectives))


def rank_and_crowding(pop: list[Individual]) -> list[list[int]]:
    n=len(pop); defeated=[[] for _ in pop]; loss=np.zeros(n,int); fronts=[[]]
    for i in range(n):
        for j in range(i+1,n):
            if dominates(pop[i],pop[j]): defeated[i].append(j); loss[j]+=1
            elif dominates(pop[j],pop[i]): defeated[j].append(i); loss[i]+=1
    fronts[0]=[i for i in range(n) if loss[i]==0]
    while fronts[-1]:
        nxt=[]
        for i in fronts[-1]:
            for j in defeated[i]:
                loss[j]-=1
                if loss[j]==0:nxt.append(j)
        fronts.append(nxt)
    fronts.pop()
    for level,front in enumerate(fronts):
        for i in front:pop[i].rank,pop[i].crowding=level,0.
        valid=[i for i in front if pop[i].valid]
        if len(valid)<=2:
            for i in valid:pop[i].crowding=np.inf
            continue
        for axis in range(2):
            order=sorted(valid,key=lambda i:pop[i].objectives[axis]); lo,hi=pop[order[0]].objectives[axis],pop[order[-1]].objectives[axis]
            if hi<=lo:continue
            pop[order[0]].crowding=pop[order[-1]].crowding=np.inf
            for k in range(1,len(order)-1):
                if np.isfinite(pop[order[k]].crowding):pop[order[k]].crowding+=(pop[order[k+1]].objectives[axis]-pop[order[k-1]].objectives[axis])/(hi-lo)
    return fronts


def survivors(pool: list[Individual],size:int)->list[Individual]:
    result=[]
    for front in rank_and_crowding(pool):
        front.sort(key=lambda i:pool[i].crowding,reverse=True); result.extend(pool[i].copy() for i in front[:size-len(result)])
        if len(result)==size:break
    return result


def score(i: Individual,style:IslandStyle)->float:
    if not i.valid:return np.inf
    if style.emphasis=="joint":return max(i.result["dz_peak_m"]/10e-6,i.result["barrier_ev"]/10e-3)
    return float(np.dot(np.asarray(style.weights),i.objectives))


def tournament(pop:list[Individual],style:IslandStyle,rng:np.random.Generator)->Individual:
    a,b=(pop[int(k)] for k in rng.integers(0,len(pop),2))
    if rng.random()<.5:return a if score(a,style)<score(b,style) else b
    if a.rank!=b.rank:return a if a.rank<b.rank else b
    if a.crowding!=b.crowding:return a if a.crowding>b.crowding else b
    return a if score(a,style)<score(b,style) else b


def anneal(style:IslandStyle,f:float)->float:
    if f<=.75:return style.explore
    q=(f-.75)/.25
    return style.final+.5*(style.explore-style.final)*(1+math.cos(math.pi*q))


def sigmas(style:IslandStyle,fraction:float)->np.ndarray:
    scale=anneal(style,fraction); v=np.zeros(N_GENES)
    v[GAPS]=.34*scale; v[INNER]=8e-6*scale; v[OUTER]=8e-6*scale
    v[LOCK]=22e-6*scale; v[CENTER_IN:CENTER_OUT+1]=9e-6*scale; v[START]=10e-6*scale
    v[LENGTH]=24e-6*scale; v[POWER]=.35*scale; v[BULGE]=10e-6*scale; v[BULGE_CENTER]=18e-6*scale; v[BULGE_WIDTH]=12e-6*scale
    if style.emphasis=="inner":v[INNER]*=1.8
    elif style.emphasis=="outer":v[OUTER]*=1.8
    elif style.emphasis=="x":v[GAPS]*=2.3;v[LOCK]*=1.7
    elif style.emphasis=="inner_x":v[INNER]*=1.7;v[GAPS]*=1.5
    elif style.emphasis=="outer_x":v[OUTER]*=1.7;v[GAPS]*=1.5
    elif style.emphasis=="central":v[CENTER_IN:START+1]*=2.0
    elif style.emphasis=="wide":v*=1.35
    elif style.emphasis=="local":v*=.55
    return v


def mutate(
    parent: np.ndarray,
    style: IslandStyle,
    rng: np.random.Generator,
    fraction: float,
    burst: bool = False,
    burst_mutation_multiplier: float = 1.0,
) -> np.ndarray:
    x = parent.copy()

    sigma = sigmas(style, fraction)
    if burst:
        sigma *= burst_mutation_multiplier

    chance = np.full(N_GENES, 0.55)

    if style.emphasis in ("x", "inner_x", "outer_x"):
        chance[GAPS] = 0.88

    if style.emphasis == "inner":
        chance[INNER] = 0.88

    if style.emphasis == "outer":
        chance[OUTER] = 0.88

    if burst:
        chance = np.maximum(chance, 0.82)
        chance[GAPS] = 0.92
        chance[INNER] = 0.88
        chance[OUTER] = 0.88
        chance[LOCK] = 0.92
        chance[CENTER_IN:CENTER_OUT + 1] = 0.90
        chance[START:LENGTH + 1] = 0.85

    active = rng.random(N_GENES) < chance

    x[active] += rng.normal(
        0.0,
        sigma[active],
    )

    return repair(x)


def block_crossover(a:np.ndarray,b:np.ndarray,rng:np.random.Generator)->np.ndarray:
    out=np.empty(N_GENES)
    for block in (GAPS,INNER,OUTER,slice(LOCK,N_GENES)):
        alpha=rng.uniform(-.10,1.10);out[block]=alpha*a[block]+(1-alpha)*b[block]
    return repair(out)


def serialize(i:Individual)->dict[str,Any]:
    knots,inner,outer=decode(i.genome)
    return dict(island=i.island,generation=i.generation,origin=i.origin,rank=i.rank,crowding=i.crowding,
                genome=i.genome.tolist(),movable_knots_m=knots.tolist(),inner_offsets_m=inner.tolist(),outer_offsets_m=outer.tolist(),lock_m=float(i.genome[LOCK]),**i.result)


def save_csv(rows:list[dict[str,Any]],path:Path)->None:
    path.parent.mkdir(parents=True,exist_ok=True)
    if not rows:path.write_text("",encoding="utf-8");return
    keys=sorted(set().union(*(row.keys() for row in rows)))
    with path.open("w",newline="",encoding="utf-8") as fp:
        writer=csv.DictWriter(fp,fieldnames=keys,extrasaction="ignore");writer.writeheader()
        for row in rows:writer.writerow({k:json.dumps(v,allow_nan=True) if isinstance(v,(list,dict)) else v for k,v in row.items()})


def elite_rows(islands:list[Island],cfg:Settings)->list[dict[str,Any]]:
    rows=[]
    for isl in islands:
        rank_and_crowding(isl.population);best=sorted(isl.population,key=lambda i:(i.rank,-i.crowding,score(i,isl.style)))[:cfg.retain_per_island]
        rows.extend(serialize(i) for i in best)
    return rows


def draw_geometry(ax,row:dict[str,Any],label:str)->None:
    genome=repair(np.asarray(json.loads(row["genome"]) if isinstance(row["genome"],str) else row["genome"],float)); p=parameters(genome)
    s=np.linspace(0,260e-6,900);rin,rout=p.rail_boundaries_m(s)
    for theta in (0.,np.pi/2,np.pi,3*np.pi/2):
        c,q=np.cos(theta),np.sin(theta);x1,y1=s*c-rin*q,s*q+rin*c;x2,y2=s*c-rout*q,s*q+rout*c
        ax.fill(np.r_[x1,x2[::-1]]*1e6,np.r_[y1,y2[::-1]]*1e6,color="#db4f4f",ec="black",lw=.35,alpha=.90)
    knots,_,_=decode(genome); ki,ko=p.rail_boundaries_m(knots);ax.plot(knots*1e6,ki*1e6,"ko",ms=2.5);ax.plot(knots*1e6,ko*1e6,"wo",mec="black",ms=2.5)
    ax.axhline(0,color=".7",lw=.35);ax.axvline(0,color=".7",lw=.35);ax.set(xlim=(-260,260),ylim=(-260,260),aspect="equal");ax.set_xticks([]);ax.set_yticks([])
    ax.set_title(f"{label}\ndz={float(row['dz_peak_m'])*1e6:.2f} um, U={float(row['barrier_ev'])*1e3:.2f} meV\nlock={float(row['lock_m'])*1e6:.0f} um",fontsize=8)


