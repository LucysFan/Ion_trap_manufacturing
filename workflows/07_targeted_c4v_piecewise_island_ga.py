def main() -> None:
    args = parser().parse_args()
    backend = available_backend(args.backend)
    if not backend.available:
        raise RuntimeError(backend.reason)
    if not 1 <= args.islands <= len(STYLES):
        raise ValueError(f"--islands must be 1..{len(STYLES)}")
    if args.population < 8 or min(args.offspring, args.generations, args.coarse_points,
                                  args.fine_points, args.max_panels) < 1:
        raise ValueError("population must be >=8 and all numerical options positive")
    cfg = Settings(backend.selected, args.islands, args.population, args.offspring,
                   args.generations, args.migration_interval, args.migrants,
                   args.checkpoint_interval, args.seed, args.coarse_points,
                   args.fine_points, args.fine_top, args.max_panels, args.fast,
                   args.output_dir)
    cfg.output_dir.mkdir(parents=True, exist_ok=True)
    (cfg.output_dir / "settings.json").write_text(json.dumps(dict(
        backend=backend.as_dict(), knots_m=KNOTS_M.tolist(),
        rf_peak_v=cfg.rf_peak_v, rf_omega_rad_s=RF_ANGULAR_FREQUENCY_RAD_S,
        target_z_m=cfg.target_z_m, dz_limit_m=cfg.dz_limit_m,
        barrier_limit_ev=cfg.barrier_limit_ev, coarse_points=cfg.coarse_points,
        fine_points=cfg.fine_points, fast=cfg.fast), indent=2), encoding="utf-8")
    print("Piecewise-linear open-centre C4v island GA | backend:", backend.selected,
          "| device:", backend.device_name, flush=True)
    print("Discovery: Pareto(dz, barrier). Fine certification: dz<3 um AND barrier<1 meV.")

    master = np.random.default_rng(cfg.seed)
    seeds = seed_genomes()
    cache: dict[tuple[float, ...], dict[str, Any]] = {}
    best_z: tuple[np.ndarray, dict[str, Any]] | None = None
    best_u: tuple[np.ndarray, dict[str, Any]] | None = None
    best_joint: tuple[np.ndarray, dict[str, Any]] | None = None

    def live_postfix(bar: tqdm) -> None:
        if best_z is None or best_u is None:
            bar.set_postfix_str("waiting for valid trace", refresh=False)
            return
        entries = {
            "dz": f'{best_z[1]["dz_peak_m"]*1e6:.2f}um/U{best_z[1]["barrier_ev"]*1e3:.1f}',
            "U": f'{best_u[1]["barrier_ev"]*1e3:.2f}meV/dz{best_u[1]["dz_peak_m"]*1e6:.1f}',
        }
        if best_joint is not None:
            entries["joint"] = f'dz{best_joint[1]["dz_peak_m"]*1e6:.2f}/U{best_joint[1]["barrier_ev"]*1e3:.2f}'
        bar.set_postfix(entries, refresh=False)

    def coarse(x: np.ndarray, bar: tqdm | None = None) -> dict[str, Any]:
        nonlocal best_z, best_u, best_joint
        x = repair(x)
        key = tuple(np.round(x, 12))
        if key not in cache:
            cache[key], _ = evaluate(x, cfg, stage="coarse")
        result = dict(cache[key])
        changed = False
        if result["valid"]:
            if best_z is None or result["dz_peak_m"] < best_z[1]["dz_peak_m"]:
                best_z = (x.copy(), result.copy()); changed = True
            if best_u is None or result["barrier_ev"] < best_u[1]["barrier_ev"]:
                best_u = (x.copy(), result.copy()); changed = True
            joint_score = max(result["dz_peak_m"]/10e-6, result["barrier_ev"]/10e-3)
            if best_joint is None or joint_score < max(best_joint[1]["dz_peak_m"]/10e-6,
                                                       best_joint[1]["barrier_ev"]/10e-3):
                best_joint = (x.copy(), result.copy()); changed = True
        if changed and best_z is not None and best_u is not None and best_joint is not None:
            payload = dict(
                best_dz=dict(genome=best_z[0].tolist(), **best_z[1]),
                best_barrier=dict(genome=best_u[0].tolist(), **best_u[1]),
                best_10x10_compromise=dict(genome=best_joint[0].tolist(), **best_joint[1]),
            )
            (cfg.output_dir / "best_live_coarse.json").write_text(
                json.dumps(payload, indent=2), encoding="utf-8")
        if bar is not None:
            live_postfix(bar)
        return result

    islands: list[Island] = []
    with tqdm(total=cfg.islands*cfg.population, desc="Initial BEM", unit="candidate") as bar:
        for island_id, style in enumerate(STYLES[:cfg.islands]):
            rng = np.random.default_rng(int(master.integers(0, 2**32-1)))
            population: list[Individual] = []
            for name, x in seeds:
                if len(population) == cfg.population:
                    break
                x = repair(x)
                population.append(Individual(x, coarse(x, bar), island_id, 0, name))
                bar.update()
            while len(population) < cfg.population:
                seed = seeds[int(rng.integers(len(seeds)))][1]
                x = repair(seed + rng.normal(0.0, style.initial_sigma*(HIGH-LOW)))
                population.append(Individual(x, coarse(x, bar), island_id, 0, "initial"))
                bar.update()
            rank_and_crowding(population)
            islands.append(Island(style, rng, population))

    all_initial = [x for island in islands for x in island.population]
    if not any(x.valid for x in all_initial):
        reasons = sorted({x.result["reason"] for x in all_initial})
        raise RuntimeError("No valid initial geometry: " + repr(reasons[:20]))

    archive: list[Individual] = []
    history: list[dict[str, Any]] = []

    def update_archive(new: list[Individual]) -> None:
        nonlocal archive
        unique = {tuple(np.round(i.genome, 12)): i.copy() for i in archive+new if i.valid}
        pool = list(unique.values())
        if not pool:
            archive = []
            return
        archive = [pool[k].copy() for k in rank_and_crowding(pool)[0]]
        archive.sort(key=lambda i: -i.crowding)
        archive = archive[:512]

    def summary(generation: int) -> dict[str, Any]:
        valid = [x for island in islands for x in island.population if x.valid]
        z = min(valid, key=lambda i: i.result["dz_peak_m"])
        u = min(valid, key=lambda i: i.result["barrier_ev"])
        j = min(valid, key=lambda i: max(i.result["dz_peak_m"]/10e-6, i.result["barrier_ev"]/10e-3))
        return dict(generation=generation, valid=len(valid), archive=len(archive),
                    best_dz_um=z.result["dz_peak_m"]*1e6,
                    U_at_best_dz_mev=z.result["barrier_ev"]*1e3,
                    best_U_mev=u.result["barrier_ev"]*1e3,
                    dz_at_best_U_um=u.result["dz_peak_m"]*1e6,
                    compromise_dz_um=j.result["dz_peak_m"]*1e6,
                    compromise_U_mev=j.result["barrier_ev"]*1e3,
                    coarse_joint_hits=sum(i.result["dz_peak_m"] < cfg.dz_limit_m and
                                          i.result["barrier_ev"] < cfg.barrier_limit_ev for i in valid),
                    unique_evaluations=len(cache))

    update_archive(all_initial)
    history.append(summary(0)); print("G000", history[-1], flush=True)

    for generation in range(1, cfg.generations+1):
        following: list[Island] = []
        with tqdm(total=cfg.islands*cfg.offspring, desc=f"Generation {generation}", unit="candidate") as bar:
            for island_id, island in enumerate(islands):
                rank_and_crowding(island.population)
                children: list[Individual] = []
                while len(children) < cfg.offspring:
                    a = tournament(island.population, island.style, island.rng)
                    if island.rng.random() < .90:
                        b = tournament(island.population, island.style, island.rng)
                        alpha = island.rng.uniform(-.15, 1.15, N_GENES)
                        genome = repair(alpha*a.genome + (1.0-alpha)*b.genome)
                        origin = "crossover"
                    else:
                        genome = a.genome.copy()
                        origin = "clone"
                    genome = mutate(genome, island.style, island.rng, generation/cfg.generations)
                    children.append(Individual(genome, coarse(genome, bar), island_id,
                                               generation, origin))
                    bar.update()
                following.append(Island(island.style, island.rng,
                                        survive(island.population+children, cfg.population)))
        islands = following
        if cfg.migration_interval > 0 and generation % cfg.migration_interval == 0 and len(islands) > 1:
            sent = []
            for island in islands:
                rank_and_crowding(island.population)
                sent.append([i.copy() for i in sorted(island.population,
                            key=lambda i: (i.rank, -i.crowding, style_score(i, island.style)))[:cfg.migrants]])
            for source, migrants in enumerate(sent):
                destination = (source+1) % len(islands)
                target = islands[destination]
                islands[destination] = Island(target.style, target.rng,
                                              survive(target.population+migrants, cfg.population))
        update_archive([x for island in islands for x in island.population])
        history.append(summary(generation)); print(f"G{generation:03d}", history[-1], flush=True)
        save_csv(history, cfg.output_dir / "history.csv")
        save_csv([record(x) for x in archive], cfg.output_dir / "pareto_coarse.csv")
        if generation % cfg.checkpoint_interval == 0 or generation == cfg.generations:
            save_csv([record(x) for island in islands for x in island.population],
                     cfg.output_dir / f"population_gen_{generation:04d}.csv")

    if not archive:
        print("No archive candidates; inspect checkpoints.")
        return
    chosen = sorted(archive, key=lambda i: i.result["dz_peak_m"])[:cfg.fine_top]
    chosen += sorted(archive, key=lambda i: i.result["barrier_ev"])[:cfg.fine_top]
    chosen += sorted(archive, key=lambda i: max(i.objective))[:cfg.fine_top]
    unique = {tuple(np.round(i.genome, 12)): i for i in chosen}
    fine_rows: list[dict[str, Any]] = []
    for number, candidate in enumerate(tqdm(unique.values(), desc="Fine validation", unit="candidate"), 1):
        result, data = evaluate(candidate.genome, cfg, stage="fine", retain=True)
        row = dict(candidate=number, genome=candidate.genome.tolist(), **result)
        fine_rows.append(row)
        if data is not None:
            directory = cfg.output_dir / f"fine_{number:03d}"
            directory.mkdir(exist_ok=True)
            draw_fine(data, result, directory)
            (directory / "result.json").write_text(json.dumps(row, indent=2), encoding="utf-8")
    save_csv(fine_rows, cfg.output_dir / "fine_validation.csv")
    verified = [row for row in fine_rows if row["verified"]]
    (cfg.output_dir / "verified_hits.json").write_text(json.dumps(verified, indent=2), encoding="utf-8")
    print(f"Fine-verified joint hits: {len(verified)}; results: {cfg.output_dir}")


