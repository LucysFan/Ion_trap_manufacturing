# Boundary coordinates on one C4v fundamental arm. The first / last values
# are fixed to zero offsets; all interior values are independently mutable.
KNOTS_M = np.array([0, 5, 10, 15, 20, 30, 45, 60, 90, 120, 150, 210], dtype=float) * 1e-6
N_EDGE = len(KNOTS_M) - 2
INNER = slice(0, N_EDGE)
OUTER = slice(N_EDGE, 2 * N_EDGE)
CENTER_IN, CENTER_OUT, START, LENGTH, POWER, BULGE, BULGE_CENTER, BULGE_WIDTH = range(2 * N_EDGE, 2 * N_EDGE + 8)
N_GENES = 2 * N_EDGE + 8

# [inner knot offsets | outer knot offsets | central/global geometry]
LOW = np.array([-35e-6] * (2 * N_EDGE) + [-50e-6, -8e-6, 5e-6, 55e-6, .65, -35e-6, 8e-6, 6e-6])
HIGH = np.array([35e-6] * (2 * N_EDGE) + [-3e-6, 65e-6, 60e-6, 330e-6, 5.5, 35e-6, 145e-6, 85e-6])


