"""Open-centre C4v X-junction search with piecewise-linear inner/outer RF edges.

This is a complete replacement workflow. It deliberately uses a free, locally
piecewise-linear genome for both RF boundaries (not polynomials). Four copies
of one fundamental contour are generated by the project C4v template. No
central RF cross is inserted.

Discovery: nondominated NSGA-II on (peak |z-z_target|, RF barrier).
Certification: only fine mesh + complete trace + dz < 3 um and barrier < 1 meV.
"""
