def reject(reason: str, stage: str) -> dict[str, Any]:
    return dict(valid=False, verified=False, reason=reason, stage=stage,
                dz_peak_m=np.inf, dz_rms_m=np.inf, barrier_ev=np.inf,
                lateral_peak_m=np.inf, panels=0, points=0, converged=0)


def build_mesh(parameters: Any, fast: bool):
    if fast:
        return build_geometry_aware_quadtree_x_junction_bem(
            parameters, central_half_extent_m=145e-6, central_max_cell_m=46e-6,
            boundary_max_cell_m=17e-6, outer_max_cell_m=180e-6, min_cell_m=8e-6)
    return build_geometry_aware_quadtree_x_junction_bem(
        parameters, central_half_extent_m=180e-6, central_max_cell_m=30e-6,
        boundary_max_cell_m=10e-6, outer_max_cell_m=180e-6, min_cell_m=5e-6)


def evaluate(genome: np.ndarray, cfg: Settings, stage="coarse", retain=False):
    x = repair(genome)
    try:
        p = make_parameters(x)
        mfg = check_x_junction_manufacturability(p)
        if not mfg.valid:
            return reject("geometry: " + "; ".join(map(str, mfg.messages)), stage), None
        s = np.linspace(0, p.arm_length_m, 2001)
        r_in, r_out = p.rail_boundaries_m(s)
        width = r_out - r_in
        if np.min(r_in) <= 0.5e-6:
            return reject("inner edge enters central clearance", stage), None
        if np.min(width) < 18e-6:
            return reject("RF rail narrower than 18 um", stage), None
        model = build_mesh(p, cfg.fast and stage == "coarse")
        if model.n_panels > cfg.max_panels:
            return reject(f"panel limit {model.n_panels}>{cfg.max_panels}", stage), None
        bem = FixedMeshBEM(model.bem.panels_m, backend=cfg.backend)
        bem.assemble(block_rows=64)
        bem.factorize()
        bem.release_matrix()
        charge = bem.solve_masks(model.bem.electrode_voltages_v)
        field = BEMField(bem, charge)
        count = cfg.fine_points if stage == "fine" else cfg.coarse_points
        xs = np.linspace(-350e-6, 350e-6, count)
        trace = trace_rf_transverse_minimum(
            field, xs, initial_y_m=0.0, initial_z_m=cfg.target_z_m,
            residual_tolerance_v_m=1e-3, max_transverse_shift_m=25e-6)
        converged = np.asarray(trace.converged, dtype=bool)
        z = np.asarray(trace.z_m, dtype=float)
        y = np.asarray(trace.y_m, dtype=float)
        if not trace.valid or converged.shape != (count,) or not np.all(converged):
            return reject(f"incomplete trace {int(np.sum(converged))}/{count}", stage), None
        if not np.all(np.isfinite(z)) or not np.all(np.isfinite(y)):
            return reject("nonfinite null trace", stage), None
        potential = np.asarray(pseudopotential_profile_ev(
            field, trace, rf_voltage_peak_v=cfg.rf_peak_v,
            rf_angular_frequency_rad_s=RF_ANGULAR_FREQUENCY_RAD_S), dtype=float)
        barrier = compute_barrier_metrics(potential, trace)
        if not barrier.valid or potential.shape != (count,) or not np.all(np.isfinite(potential)):
            return reject("invalid pseudopotential profile", stage), None
        dz = z - cfg.target_z_m
        dz_peak = float(np.max(np.abs(dz)))
        dz_rms = float(np.sqrt(np.mean(dz**2)))
        lateral_peak = float(np.max(np.abs(y)))
        barrier_ev = float(barrier.barrier_height_ev)
        if not np.all(np.isfinite([dz_peak, dz_rms, lateral_peak, barrier_ev])):
            return reject("nonfinite physical metric", stage), None
        result = dict(
            valid=True,
            verified=bool(stage == "fine" and dz_peak < cfg.dz_limit_m
                          and barrier_ev < cfg.barrier_limit_ev
                          and lateral_peak < cfg.lateral_limit_m),
            reason="ok", stage=stage, backend=bem.backend_name,
            dz_peak_m=dz_peak, dz_rms_m=dz_rms, barrier_ev=barrier_ev,
            lateral_peak_m=lateral_peak,
            barrier_reference_ev=float(barrier.reference_energy_ev),
            panels=int(model.n_panels), points=count, converged=int(np.sum(converged)))
        return result, (model, trace, potential) if retain else None
    except Exception as error:
        if cfg.backend == "cuda" and "out of memory" in str(error).lower():
            raise RuntimeError("CUDA OOM: reduce --max-panels or use --fast") from error
        return reject(f"{type(error).__name__}: {error}", stage), None


def dominates(a: Individual, b: Individual) -> bool:
    if a.valid != b.valid:
        return a.valid
    if not a.valid:
        return False
    return bool(np.all(a.objective <= b.objective) and np.any(a.objective < b.objective))


def rank_and_crowding(population: list[Individual]) -> list[list[int]]:
    count = len(population)
    dominates_set = [[] for _ in population]
    losses = np.zeros(count, dtype=int)
    fronts: list[list[int]] = [[]]
    for i in range(count):
        for j in range(i + 1, count):
            if dominates(population[i], population[j]):
                dominates_set[i].append(j)
                losses[j] += 1
            elif dominates(population[j], population[i]):
                dominates_set[j].append(i)
                losses[i] += 1
    fronts[0] = [i for i in range(count) if losses[i] == 0]
    while fronts[-1]:
        next_front: list[int] = []
        for i in fronts[-1]:
            for j in dominates_set[i]:
                losses[j] -= 1
                if losses[j] == 0:
                    next_front.append(j)
        fronts.append(next_front)
    fronts.pop()
    for level, front in enumerate(fronts):
        for i in front:
            population[i].rank = level
            population[i].crowding = 0.0
        valid = [i for i in front if population[i].valid]
        if len(valid) <= 2:
            for i in valid:
                population[i].crowding = np.inf
            continue
        for axis in range(2):
            order = sorted(valid, key=lambda i: population[i].objective[axis])
            low = population[order[0]].objective[axis]
            high = population[order[-1]].objective[axis]
            if high <= low:
                continue
            population[order[0]].crowding = np.inf
            population[order[-1]].crowding = np.inf
            for j in range(1, len(order) - 1):
                item = population[order[j]]
                if np.isfinite(item.crowding):
                    item.crowding += ((population[order[j+1]].objective[axis]
                                       - population[order[j-1]].objective[axis]) / (high - low))
    return fronts


def survive(pool: list[Individual], size: int) -> list[Individual]:
    fronts = rank_and_crowding(pool)
    output: list[Individual] = []
    for front in fronts:
        front.sort(key=lambda i: pool[i].crowding, reverse=True)
        output.extend(pool[i].copy() for i in front[:size-len(output)])
        if len(output) == size:
            return output
    return output


def style_score(item: Individual, style: IslandStyle) -> float:
    return np.inf if not item.valid else float(np.dot(style.objective_weights, item.objective))


def tournament(population: list[Individual], style: IslandStyle, rng: np.random.Generator) -> Individual:
    a, b = (population[int(i)] for i in rng.integers(0, len(population), 2))
    if rng.random() < .50:
        return a if style_score(a, style) < style_score(b, style) else b
    if a.rank != b.rank:
        return a if a.rank < b.rank else b
    if a.crowding != b.crowding:
        return a if a.crowding > b.crowding else b
    return a if style_score(a, style) < style_score(b, style) else b


def mutate(parent: np.ndarray, style: IslandStyle, rng: np.random.Generator, progress: float) -> np.ndarray:
    x = parent.copy()
    p = np.full(N_GENES, .58)
    if style.emphasis == "inner":
        p[INNER] = .92
    elif style.emphasis == "outer":
        p[OUTER] = .92
    elif style.emphasis == "central":
        p[:2*N_EDGE] = .80
        p[CENTER_IN:CENTER_OUT+1] = .95
    active = rng.random(N_GENES) < p
    scale = style.mutation_sigma * (1.0 - .60 * progress)
    x[active] += rng.normal(0.0, (HIGH-LOW)[active] * scale)
    # Coordinated but still piecewise-linear local kicks; not smoothing.
    shape = np.array([.28, .58, .90, 1.0, .86, .62, .38, .20, .09, .0])
    local_sigma = 15e-6 * (1.0 - .50 * progress)
    if style.emphasis in ("inner", "both", "central"):
        x[INNER] += rng.normal(0.0, local_sigma) * shape
    if style.emphasis in ("outer", "both", "central"):
        x[OUTER] += rng.normal(0.0, local_sigma) * shape
    return repair(x)


def record(individual: Individual) -> dict[str, Any]:
    return dict(island=individual.island, generation=individual.generation,
                origin=individual.origin, rank=individual.rank,
                crowding=individual.crowding, genome=individual.genome.tolist(),
                **individual.result)


def save_csv(rows: list[dict[str, Any]], filename: Path) -> None:
    filename.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        filename.write_text("", encoding="utf-8")
        return
    keys = sorted(set().union(*(row.keys() for row in rows)))
    with filename.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=keys, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({key: json.dumps(value, allow_nan=True)
                             if isinstance(value, (dict, list)) else value
                             for key, value in row.items()})


def draw_fine(data: tuple[Any, Any, np.ndarray], result: dict[str, Any], directory: Path) -> None:
    model, trace, potential = data
    panels = np.asarray(model.bem.panels_m)
    rf = np.asarray(model.bem.electrode_voltages_v) > .5
    rectangles = [Rectangle((p[0]*1e6, p[2]*1e6), (p[1]-p[0])*1e6, (p[3]-p[2])*1e6)
                  for p in panels]
    fig, ax = plt.subplots(figsize=(7, 7))
    collection = PatchCollection(rectangles, array=rf.astype(float), cmap="RdYlBu_r")
    ax.add_collection(collection)
    ax.plot(np.asarray(trace.x_m)*1e6, np.asarray(trace.y_m)*1e6, "k-", lw=1.3)
    ax.set(xlim=(-230, 230), ylim=(-230, 230), xlabel="x [um]", ylabel="y [um]",
           title="Open-centre C4v RF mask; piecewise-linear edge genome")
    ax.set_aspect("equal")
    fig.colorbar(collection, ax=ax)
    fig.tight_layout()
    fig.savefig(directory / "layout.png", dpi=170)
    plt.close(fig)
    x = np.asarray(trace.x_m) * 1e6
    fig, axes = plt.subplots(3, 1, figsize=(9, 9), sharex=True)
    axes[0].plot(x, (np.asarray(trace.z_m)-TARGET_ION_HEIGHT_M)*1e6)
    axes[0].axhline(3.0, color="r", ls="--"); axes[0].axhline(-3.0, color="r", ls="--")
    axes[0].set_ylabel("z-target [um]")
    axes[1].plot(x, (potential-result["barrier_reference_ev"])*1e3)
    axes[1].axhline(1.0, color="r", ls="--")
    axes[1].set_ylabel("RF pseudo - ref [meV]")
    axes[2].plot(x, np.asarray(trace.y_m)*1e6)
    axes[2].set_ylabel("y [um]"); axes[2].set_xlabel("x [um]")
    for ax in axes:
        ax.grid(alpha=.25)
    fig.tight_layout()
    fig.savefig(directory / "profiles.png", dpi=170)
    plt.close(fig)


