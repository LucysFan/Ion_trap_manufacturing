@dataclass
class Individual:
    genome: np.ndarray
    result: dict[str, Any]
    island: int
    generation: int
    origin: str
    rank: int = 0
    crowding: float = 0.0

    @property
    def valid(self) -> bool:
        return bool(self.result["valid"])

    @property
    def objective(self) -> np.ndarray:
        if not self.valid:
            return np.array([np.inf, np.inf])
        return np.array([self.result["dz_peak_m"] / 3e-6,
                         self.result["barrier_ev"] / 1e-3], dtype=float)

    def copy(self) -> "Individual":
        return Individual(self.genome.copy(), dict(self.result), self.island,
                          self.generation, self.origin, self.rank, self.crowding)


@dataclass
class Island:
    style: IslandStyle
    rng: np.random.Generator
    population: list[Individual]


class BEMField:
    def __init__(self, bem: FixedMeshBEM, charge: Any):
        self.bem = bem
        self.charge = charge

    def electric_field(self, x_m: float, y_m: float, z_m: float):
        field = self.bem.field_batch(np.array([x_m]), np.array([y_m]),
                                     np.array([z_m]), self.charge)
        return tuple(map(float, self.bem.asnumpy(field)[0, 0]))


def repair(genome: np.ndarray) -> np.ndarray:
    """Clip values and reject only mesh-aliasing / near-vertical edge artifacts.

    The result remains piecewise-linear. This does not smooth or spline the
    contour; it merely bounds slope so a feature spans more than one mesh cell.
    """
    x = np.asarray(genome, dtype=float).copy()
    if x.shape != (N_GENES,) or not np.all(np.isfinite(x)):
        raise ValueError(f"Genome must contain {N_GENES} finite values")
    x = np.clip(x, LOW, HIGH)
    max_abs_slope = 1.25
    for edge in (INNER, OUTER):
        values = np.r_[0.0, x[edge], 0.0]
        for _ in range(4):
            for i in range(1, len(values)):
                limit = max_abs_slope * (KNOTS_M[i] - KNOTS_M[i-1])
                values[i] = np.clip(values[i], values[i-1]-limit, values[i-1]+limit)
            for i in range(len(values)-2, -1, -1):
                limit = max_abs_slope * (KNOTS_M[i+1] - KNOTS_M[i])
                values[i] = np.clip(values[i], values[i+1]-limit, values[i+1]+limit)
        x[edge] = values[1:-1]
    return x


def baseline() -> np.ndarray:
    x = np.zeros(N_GENES)
    x[CENTER_IN:] = [-25e-6, 20e-6, 30e-6, 150e-6, 2.0, 0.0, 70e-6, 25e-6]
    return x


def seed_genomes() -> list[tuple[str, np.ndarray]]:
    base = baseline()
    h = base.copy()
    h[[6, 7, 8]] = [-12e-6, -12e-6, -9e-6]
    b = base.copy()
    b[[6, 7, 8]] = [-12e-6, -8e-6, -9e-6]
    both = base.copy()
    both[[4, 5, 6, 7, 8]] = [-8e-6, -15e-6, -18e-6, -13e-6, -7e-6]
    both[N_EDGE + np.array([4, 5, 6, 7, 8])] = [5e-6, 10e-6, 13e-6, 9e-6, 4e-6]
    return [("baseline", base), ("height_seed", h), ("barrier_seed", b),
            ("coupled_piecewise_seed", both)]


